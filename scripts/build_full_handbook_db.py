def main():
    with open("data/fish_database.json", "r", encoding="utf-8") as f:
        base_db = json.load(f)

    assert len(base_db) == 27, f"Expected 27 species, got {len(base_db)}"
    out = []
    for sp in base_db:
        slug = sp["slug"]
        assert slug in HANDBOOK_EXTRA, f"Missing handbook entry for {slug}"
        merged = dict(sp)
        merged.update(HANDBOOK_EXTRA[slug])
        out.append(merged)

    payload = {
        "title": "WorldOfVikingCraft — Полный справочник рыб и поклёвок (27 видов)",
        "species_count": len(out),
        "base_bite_types": BASE_FIVE_TYPES,
        "species": out,
    }
    os.makedirs("data", exist_ok=True)
    with open("data/fish_handbook_27.json", "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
    print(f"Wrote data/fish_handbook_27.json with {len(out)} species and {len(BASE_FIVE_TYPES)} base bite types.")


if __name__ == "__main__":
    main()
